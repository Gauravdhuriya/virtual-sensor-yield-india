"""Build every table and figure from the saved result files. No number is typed by hand.

  python make_report.py [--quick]   ->  report/results.md, report/results.json, report/fig_*.png
"""
import argparse, json, os, pickle
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import adt_india as adt

ap = argparse.ArgumentParser(); ap.add_argument("--quick", action="store_true"); args = ap.parse_args()
SRC = "out_quick" if args.quick else "out"
OUT = "report_quick" if args.quick else "report"
os.makedirs(OUT, exist_ok=True)
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "figure.dpi": 200,
                     "savefig.bbox": "tight"})
C = dict(raw="#4C72B0", latent="#DD8452", both="#55A868")
ARM = dict(raw="Raw", latent="Latent", both="Raw + latent")
REG = dict(level_env="Yield level, climate only", level_ymem="Yield level, with yield memory (H_t, Eq. 11)",
           anom="Yield anomaly, climate only")
UNITS = dict(level_env="t/ha", level_ymem="t/ha", anom="log ratio")
NN = dict(lstm="LSTM", tf="Transformer", pgnn="Physics-guided NN")


def load(name):
    p = f"{SRC}/{name}.pkl"
    return pickle.load(open(p, "rb")) if os.path.exists(p) else {}

def pm(t, d=3):
    return f"{t[0]:.{d}f} ± {t[1]:.{d}f}"

def fmt_p(p):
    return "n/a" if np.isnan(p) else ("<0.001" if p < 0.001 else f"{p:.3f}")

S = adt.summarise
main = {**load("main_xgb"), **load("main_rf")}
nnr, abl, sens = load("nn"), load("abl"), load("sens")
info = json.load(open(f"{SRC}/info.json"))
md, js = [], dict(info=info)

md.append("# Results - Indian district experiments (generated by make_report.py)\n")
md.append(f"- Samples: {info['n_samples']} district-crop-years, {info['n_districts']} districts, {info['n_states']} states, "
          f"{info['n_series']} district-crop series, target years {info['years'][0]}-{info['years'][1]}.")
md.append("- Per crop: " + ", ".join(f"{k} {v}" for k, v in info["per_crop"].items()) + ".")
md.append(f"- Weather: {info['weather_districts']} districts, {info['weather_days']} days; {info['weather_missing_values']} missing daily "
          f"values filled with day-of-year means; soil pH available for {info['districts_with_ph']} districts (others: state median).")
md.append(f"- Yield records dropped as implausible (> 5 x crop median): {info['dropped_outliers']}.")
if "sensor_stats" in info:
    st = info["sensor_stats"]
    md.append(f"- Daily sensor behaviour: VSSM mean {st['VSSM']['mean']:.3f} (at 0 on {100*st['VSSM']['frac_at_0']:.0f}% of days, "
              f"at 1 on {100*st['VSSM']['frac_at_1']:.0f}%); VSST mean {st['VSST']['mean']:.1f} C (SD {st['VSST']['sd']:.1f}); "
              f"VSCS mean {st['VSCS']['mean']:.3f} (SD {st['VSCS']['sd']:.3f}).")
md.append("- RMSE and MAE in t/ha for yield level, in log-ratio units for yield anomaly. Mean ± SD over seeds.\n")

# ------------------------------------------------------------------ main comparison
for regime in REG:
    rows = [(sc, m, a) for sc in adt.SCENARIOS for m in ("rf", "xgb") for a in ("raw", "latent", "both") if (m, sc, regime, a) in main]
    if not rows:
        continue
    md.append(f"\n## Main comparison - {REG[regime]}\n")
    md.append("| Scenario | Model | Input | RMSE | MAE | R2 |\n|---|---|---|---|---|---|")
    for sc, m, a in rows:
        r = S(main[(m, sc, regime, a)]["per_seed"])
        md.append(f"| {adt.SC_NAME[sc]} | {m.upper()} | {ARM[a]} | {pm(r['rmse'])} | {pm(r['mae'])} | {pm(r['r2'])} |")
        js[f"main|{m}|{sc}|{regime}|{a}"] = r

# ------------------------------------------------------------------ significance
md.append("\n## Paired significance: latent vs raw (per-unit RMSE, latent minus raw; negative = latent better)\n")
md.append("| Target | Scenario | Model | Units | Mean diff [95% CI] | Wilcoxon p | Units where latent better |\n|---|---|---|---|---|---|---|")
for regime in REG:
    for sc in adt.SCENARIOS:
        for m in ("rf", "xgb"):
            a, b = (m, sc, regime, "raw"), (m, sc, regime, "latent")
            if a in main and b in main:
                t = adt.paired_test(main[a]["unit_rmse"], main[b]["unit_rmse"])
                md.append(f"| {REG[regime]} | {adt.SC_NAME[sc]} | {m.upper()} | {t['n']} {adt.UNIT[sc]}s | "
                          f"{t['mean_diff']:+.4f} [{t['ci'][0]:+.4f}, {t['ci'][1]:+.4f}] | {fmt_p(t['p'])} | {100*t['frac_better']:.0f}% |")
                js[f"sig|{m}|{sc}|{regime}"] = t

# ------------------------------------------------------------------ neural baselines
if nnr:
    for regime in REG:
        scs = [sc for sc in adt.SCENARIOS if any(k[1] == sc and k[2] == regime for k in nnr)]
        if not scs:
            continue
        md.append(f"\n## Benchmark models - {REG[regime]}\n")
        md.append("| Scenario | Model | Input | RMSE | MAE | R2 |\n|---|---|---|---|---|---|")
        for sc in scs:
            for m, a in (("rf", "raw"), ("rf", "latent"), ("xgb", "raw"), ("xgb", "latent")):
                if (m, sc, regime, a) in main:
                    r = S(main[(m, sc, regime, a)]["per_seed"])
                    md.append(f"| {adt.SC_NAME[sc]} | {m.upper()} | {ARM[a]} | {pm(r['rmse'])} | {pm(r['mae'])} | {pm(r['r2'])} |")
            for kind, a in (("lstm", "raw"), ("lstm", "latent"), ("tf", "raw"), ("tf", "latent"), ("pgnn", "raw")):
                if (kind, sc, regime, a) in nnr:
                    r = S(nnr[(kind, sc, regime, a)]["per_seed"])
                    lab = "Raw (sensors learned inside)" if kind == "pgnn" else ARM[a]
                    md.append(f"| {adt.SC_NAME[sc]} | {NN[kind]} | {lab} | {pm(r['rmse'])} | {pm(r['mae'])} | {pm(r['r2'])} |")
                    js[f"nn|{kind}|{sc}|{regime}|{a}"] = r
    ph = [p for k, v in nnr.items() if k[0] == "pgnn" for p in v.get("phys", [])]
    if ph:
        d = pd.DataFrame(ph); N = adt.NOMINAL
        nom = dict(alpha=N["alpha"], beta=N["beta"], delta=N["delta"], lam=N["lam"], gamma=float(np.exp(-1 / N["tau"])),
                   omega1=N["omega1"], omega2=N["omega2"], omega3=1 - N["omega1"] - N["omega2"])
        md.append("\nPhysics parameters learned by the physics-guided network (mean ± SD over folds and seeds; nominal in brackets): "
                  + ", ".join(f"{c} = {d[c].mean():.4f} ± {d[c].std():.4f} [{nom[c]:.4f}]" for c in nom) + ".")
        js["pgnn_phys"] = {c: (float(d[c].mean()), float(d[c].std()), float(nom[c])) for c in nom}

# ------------------------------------------------------------------ ablation
abl_sc = [sc for sc in adt.SCENARIOS if any(k[0] == sc for k in abl)]
if abl:
    order = ["covariates only", "sensors:VSSM", "sensors:VSST", "sensors:VSCS", "sensors:VSSM+VSST", "sensors:VSSM+VSCS",
             "sensors:VSST+VSCS", "latent k=2", "raw k=2", "latent k=0", "raw k=0", "latent k=1", "raw k=1", "latent k=3", "raw k=3"]
    for regime in ("level_env", "anom"):
        md.append(f"\n## Ablation - {REG[regime]} (XGBoost unless changed in run_all.py)\n")
        md.append("| Configuration | " + " | ".join(f"{adt.SC_NAME[sc]} RMSE | {adt.SC_NAME[sc]} R2" for sc in abl_sc) + " |\n|---|" + "---|---|" * len(abl_sc))
        for name in order:
            cells = []
            for sc in abl_sc:
                r = abl.get((sc, regime, name))
                if r is None:
                    cells += ["-", "-"]
                else:
                    q = S(r["per_seed"]); cells += [pm(q["rmse"]), pm(q["r2"])]; js[f"abl|{sc}|{regime}|{name}"] = q
            lab = {"latent k=2": "sensors: all three (latent k=2)"}.get(name, name)
            md.append(f"| {lab} | " + " | ".join(cells) + " |")
    md.append(f"\n## Ablation - {REG['level_ymem']}\n")
    md.append("| Configuration | " + " | ".join(f"{adt.SC_NAME[sc]} RMSE | {adt.SC_NAME[sc]} R2" for sc in abl_sc) + " |\n|---|" + "---|---|" * len(abl_sc))
    for name in ("YA only k=2", "raw+YA k=2", "latent+YA k=1", "latent+YA k=2", "latent+YA k=3"):
        cells = []
        for sc in abl_sc:
            r = abl.get((sc, "level_ymem", name))
            if r is None:
                cells += ["-", "-"]
            else:
                q = S(r["per_seed"]); cells += [pm(q["rmse"]), pm(q["r2"])]; js[f"abl|{sc}|level_ymem|{name}"] = q
        md.append(f"| {name} | " + " | ".join(cells) + " |")

# ------------------------------------------------------------------ sensitivity
PAR = ("alpha", "beta", "lam", "tau", "delta", "omega1")
if sens:
    md.append("\n## Sensitivity of the virtual sensor parameters (latent arm, climate only; RMSE)\n")
    for sc in abl_sc:
        for regime in ("level_env", "anom"):
            if (sc, regime, "nominal", 1.0) not in sens:
                continue
            nom = S(sens[(sc, regime, "nominal", 1.0)]["per_seed"])["rmse"][0]
            raw = abl.get((sc, regime, "raw k=2"))
            rawtxt = f", raw inputs {S(raw['per_seed'])['rmse'][0]:.4f}" if raw else ""
            md.append(f"\n{adt.SC_NAME[sc]} - {REG[regime]} (nominal RMSE {nom:.4f}{rawtxt}):\n")
            md.append("| Parameter | -50% | -20% | +20% | +50% | Max change |\n|---|---|---|---|---|---|")
            for name in PAR:
                v = [S(sens[(sc, regime, name, f)]["per_seed"])["rmse"][0] if (sc, regime, name, f) in sens else np.nan
                     for f in (0.5, 0.8, 1.2, 1.5)]
                mx = np.nanmax(np.abs(np.array(v) - nom)) / nom * 100
                md.append(f"| {name} | " + " | ".join("-" if np.isnan(x) else f"{x:.4f}" for x in v) + f" | {mx:.1f}% |")
                js[f"sens|{sc}|{regime}|{name}"] = dict(values=v, nominal=nom, max_change_pct=float(mx))

open(f"{OUT}/results.md", "w", encoding="utf-8").write("\n".join(md) + "\n")
json.dump(js, open(f"{OUT}/results.json", "w"), indent=1, default=float)

# ================================================================== figures
fm = "rf" if any(k[0] == "rf" for k in main) else "xgb"
regs = [r for r in REG if any(k[0] == fm and k[2] == r for k in main)]
if regs:
    fig, axs = plt.subplots(1, len(regs), figsize=(3.6 * len(regs), 3.0), squeeze=False)
    for ax, regime in zip(axs[0], regs):
        scs = [sc for sc in adt.SCENARIOS if (fm, sc, regime, "raw") in main and (fm, sc, regime, "latent") in main]
        x = np.arange(len(scs)); w = 0.38
        for i, arm in enumerate(("raw", "latent")):
            v = [S(main[(fm, sc, regime, arm)]["per_seed"])["rmse"] for sc in scs]
            ax.bar(x + (i - 0.5) * w, [a[0] for a in v], w, yerr=[a[1] for a in v], color=C[arm], label=ARM[arm], capsize=2)
        ax.set_xticks(x); ax.set_xticklabels([adt.SC_NAME[sc].replace(" ", "\n").replace("-", "-\n") for sc in scs], fontsize=7)
        ax.set_ylabel(f"RMSE ({UNITS[regime]})"); ax.set_title(REG[regime].split(" (")[0], fontsize=8.5)
    axs[0][0].legend(frameon=False, fontsize=7)
    fig.suptitle({"rf": "Random Forest", "xgb": "XGBoost"}[fm], fontsize=9, y=1.02)
    fig.tight_layout(); fig.savefig(f"{OUT}/fig_rmse_comparison.png"); plt.close(fig)

    regs2 = [r for r in regs if (fm, "temporal", r, "latent") in main]
    if regs2:
        fig, axs = plt.subplots(1, len(regs2), figsize=(3.4 * len(regs2), 3.2), squeeze=False)
        for ax, regime in zip(axs[0], regs2):
            r = main[(fm, "temporal", regime, "latent")]
            ax.scatter(r["y"], r["pred"], s=2, alpha=0.25, color=C["latent"], rasterized=True)
            lo, hi = min(r["y"].min(), r["pred"].min()), max(r["y"].max(), r["pred"].max())
            ax.plot([lo, hi], [lo, hi], color="k", lw=0.7)
            q = S(r["per_seed"])
            ax.set_title(f"{REG[regime].split(' (')[0]}\nR2 = {q['r2'][0]:.3f}, RMSE = {q['rmse'][0]:.3f}", fontsize=8)
            ax.set_xlabel(f"Actual ({UNITS[regime]})"); ax.set_ylabel(f"Predicted ({UNITS[regime]})")
        fig.tight_layout(); fig.savefig(f"{OUT}/fig_actual_vs_predicted.png"); plt.close(fig)

        fig, axs = plt.subplots(1, len(regs2), figsize=(3.4 * len(regs2), 2.8), squeeze=False)
        for ax, regime in zip(axs[0], regs2):
            for arm in ("raw", "latent"):
                r = main.get((fm, "temporal", regime, arm))
                if r is not None:
                    e = r["pred"] - r["y"]; lim = np.percentile(np.abs(e), 99)
                    ax.hist(e, bins=np.linspace(-lim, lim, 60), histtype="step", color=C[arm], lw=1.2, label=f"{ARM[arm]} (SD {e.std():.3f})")
            ax.set_title(REG[regime].split(" (")[0], fontsize=8); ax.set_xlabel(f"Prediction error ({UNITS[regime]})")
            ax.legend(frameon=False, fontsize=6.5)
        axs[0][0].set_ylabel("Count")
        fig.tight_layout(); fig.savefig(f"{OUT}/fig_error_distribution.png"); plt.close(fig)

if abl and abl_sc:
    names = ["covariates only", "sensors:VSSM", "sensors:VSST", "sensors:VSCS", "sensors:VSSM+VSST", "sensors:VSSM+VSCS",
             "sensors:VSST+VSCS", "latent k=2", "raw k=2"]
    labs = ["No climate", "VSSM", "VSST", "VSCS", "VSSM+VSST", "VSSM+VSCS", "VSST+VSCS", "All three", "Raw weather"]
    sc = abl_sc[0]
    fig, axs = plt.subplots(1, 2, figsize=(7.4, 3.0))
    for ax, regime in zip(axs, ("level_env", "anom")):
        v = [S(abl[(sc, regime, n)]["per_seed"])["rmse"] if (sc, regime, n) in abl else (np.nan, 0) for n in names]
        ax.barh(np.arange(len(names)), [a[0] for a in v], xerr=[a[1] for a in v], color=["#999999"] + [C["latent"]] * 7 + [C["raw"]], capsize=2)
        ok = [a[0] for a in v if not np.isnan(a[0])]
        if ok:
            ax.set_xlim(min(ok) * 0.9, max(ok) * 1.05)
        ax.set_yticks(np.arange(len(names))); ax.set_yticklabels(labs if regime == "level_env" else []); ax.invert_yaxis()
        ax.set_xlabel(f"RMSE ({UNITS[regime]})"); ax.set_title(f"{REG[regime]}\n{adt.SC_NAME[sc]}", fontsize=8)
    fig.tight_layout(); fig.savefig(f"{OUT}/fig_ablation.png"); plt.close(fig)

if sens and abl_sc:
    sc = abl_sc[0]
    fig, axs = plt.subplots(1, 2, figsize=(7.4, 2.9))
    for ax, regime in zip(axs, ("level_env", "anom")):
        if (sc, regime, "nominal", 1.0) not in sens:
            continue
        nom = S(sens[(sc, regime, "nominal", 1.0)]["per_seed"])["rmse"][0]
        for name in PAR:
            pts = [(-50, 0.5), (-20, 0.8), (20, 1.2), (50, 1.5)]
            xy = [(x, S(sens[(sc, regime, name, f)]["per_seed"])["rmse"][0]) for x, f in pts if (sc, regime, name, f) in sens] + [(0, nom)]
            xy.sort(); ax.plot([a for a, _ in xy], [b for _, b in xy], marker="o", ms=3, lw=1, label=name)
        raw = abl.get((sc, regime, "raw k=2"))
        if raw:
            ax.axhline(S(raw["per_seed"])["rmse"][0], color=C["raw"], ls="--", lw=1, label="raw inputs")
        ax.set_xlabel("Parameter change (%)"); ax.set_ylabel(f"RMSE ({UNITS[regime]})")
        ax.set_title(f"{REG[regime]}\n{adt.SC_NAME[sc]}", fontsize=8)
    axs[1].legend(frameon=False, fontsize=6.5, ncol=2)
    fig.tight_layout(); fig.savefig(f"{OUT}/fig_sensitivity.png"); plt.close(fig)

# correlation of season-mean inputs and sensors with the yield anomaly
s, wx, _ = adt.load_all()
bank = adt.make_feature_bank(wx)
raw0, lat0 = adt._gather(bank["raw"], s, 0), adt._gather(bank["latent"], s, 0)
d = pd.DataFrame({n: raw0[:, 3 * i:3 * i + 3].mean(1) for i, n in enumerate(["Rain", "Temp", "Wind", "Solar", "Humidity"])})
for i, n in enumerate(adt.SENSORS):
    d[n] = lat0[:, 3 * i:3 * i + 3].mean(1)
d["Yield anomaly"] = np.log(s["y"].to_numpy() / s[["y_l1", "y_l2", "y_l3"]].mean(axis=1).to_numpy())
corr = d.corr(method="spearman")
fig, ax = plt.subplots(figsize=(4.8, 4.0))
im = ax.imshow(corr, cmap="RdBu_r", vmin=-1, vmax=1)
ax.set_xticks(range(len(corr))); ax.set_xticklabels(corr.columns, rotation=45, ha="right"); ax.set_yticks(range(len(corr))); ax.set_yticklabels(corr.columns)
for i in range(len(corr)):
    for j in range(len(corr)):
        ax.text(j, i, f"{corr.iloc[i, j]:.2f}", ha="center", va="center", fontsize=6.5, color="white" if abs(corr.iloc[i, j]) > 0.6 else "black")
for sp in ax.spines.values():
    sp.set_visible(False)
fig.colorbar(im, fraction=0.046, pad=0.04); fig.tight_layout(); fig.savefig(f"{OUT}/fig_correlation.png"); plt.close(fig)
corr.round(3).to_csv(f"{OUT}/correlation.csv")
print(f"Report written to {OUT}/ - open {OUT}/results.md")
